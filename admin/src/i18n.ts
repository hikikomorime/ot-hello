export type LocaleId = 'en' | 'pl';

export function localeFromWp(locale: string): LocaleId {
  return locale.toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

export function createTranslator(locale: LocaleId): (key: string) => string {
  const table = catalogs[locale];
  const fallback = catalogs.en;
  const wp = getConfig().i18n ?? {};
  const wpLocale = localeFromWp(getConfig().locale);

  return (key: string): string => {
    if (locale === wpLocale && wp[key]) {
      return wp[key];
    }
    return table[key] ?? fallback[key] ?? key;
  };
}
